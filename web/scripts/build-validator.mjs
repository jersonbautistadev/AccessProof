// Compiles schema/report.schema.json into a standalone ES module at build time.
// Runtime Ajv compilation uses `new Function`, which the viewer's Content Security
// Policy forbids; shipping pre-generated code keeps `script-src 'self'` strict.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const schemaUrl = new URL("../../schema/report.schema.json", import.meta.url);
const outDir = new URL("../src/generated/", import.meta.url);
const schema = JSON.parse(readFileSync(schemaUrl, "utf8"));

const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv, ["date-time"]);
const validate = ajv.compile(schema);

// Ajv's ESM output still reaches its runtime helpers through CommonJS `require`.
// Swap each one for the ES-module equivalent in src/validator-runtime.ts.
const replacements = [
  ['require("ajv/dist/runtime/equal").default', "jsonEqual"],
  ['require("ajv/dist/runtime/ucs2length").default', "codePointLength"],
  ['require("ajv-formats/dist/formats").fullFormats["date-time"]', "dateTimeFormat"],
];
let code = standaloneCode(ajv, validate);
for (const [from, to] of replacements) code = code.split(from).join(to);
if (/\brequire\(|new Function|\beval\(/.test(code)) {
  throw new Error("Generated validator still contains require(), new Function, or eval(); update the replacements.");
}

mkdirSync(outDir, { recursive: true });
writeFileSync(
  new URL("validate-report.js", outDir),
  "// Generated by scripts/build-validator.mjs from schema/report.schema.json. Do not edit.\n" +
    'import { codePointLength, dateTimeFormat, jsonEqual } from "../validator-runtime";\n' +
    code,
);
writeFileSync(
  new URL("validate-report.d.ts", outDir),
  '// Generated. Do not edit.\nimport type { ErrorObject } from "ajv";\n' +
    "declare const validate: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };\n" +
    "export default validate;\n",
);
console.log("Generated src/generated/validate-report.js");
